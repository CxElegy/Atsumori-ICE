def canvas(x0, y0, x1, y1, fill, ops):
    C = {}
    def F(a, b, c, d, ch):
        for y in range(b, d + 1):
            for x in range(a, c + 1):
                if x0 <= x <= x1 and y0 <= y <= y1:
                    C[(x, y)] = ch
    if fill:
        F(x0, y0, x1, y1, fill)
    for op in ops:
        F(*op)
    return [''.join(C.get((x, y), ' ') for x in range(x0, x1 + 1)) for y in range(y0, y1 + 1)]


